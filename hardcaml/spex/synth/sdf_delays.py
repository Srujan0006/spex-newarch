#!/usr/bin/env python3
"""Delay-annotated gate-level replay without Icarus's SDF annotator (for
synth/sdf_replay.sh). Icarus 12 aborts on this netlist with an SDF loaded
(delay.cc: vvp_fun_modpath::recv_vec4, "tmp == use_delay"), so the delays go in as one
inertial delay per cell output instead of per input-to-output path:

  output delay = pick over the cell's IOPATH delays to that output (rise and fall
                 separately) + pick over the wire delays (INTERCONNECT) from that output

with pick = max (setup side, slow corner) or, with --min, min (hold side, fast corner).
Every cell module M of the functional models is renamed M__f and wrapped by a module M
with a real parameter per output and edge (DR_<out>, DF_<out>) and
`assign #(DR, DF) out = core_out`. The netlist copy gets one defparam per annotated
instance output. Clock-tree buffers are cells too, so clock skew is in.

usage: python3 synth/sdf_delays.py [--min] SDF NETLIST MODELS_OUT NETLIST_OUT MODEL.v...
  MODEL.v: the functional cell models (synth/gl_cells.py output) and the IHP SRAM
  models; MODELS_OUT gets the renamed models plus the wrappers.
"""
import re, sys, collections

args = [a for a in sys.argv[1:] if a != "--min"]
pick = min if "--min" in sys.argv else max
sdf, nl, models_out, nl_out, models = args[0], args[1], args[2], args[3], args[4:]

def val(t):  # "(a::b)" / "(a:b:c)" / "()" -> picked float or None
    v = [float(x) for x in re.findall(r"-?\d+\.\d+", t)]
    return pick(v) if v else None

# ---- delays from the SDF ----
cell_d = collections.defaultdict(dict)     # inst -> out -> [rise, fall]
wire_d = collections.defaultdict(lambda: [None, None])  # "inst.pin" (driver) -> [r, f]
text = open(sdf).read()
for cell in re.split(r"\n \(CELL\b", text)[1:]:
    inst = re.search(r"\(INSTANCE\s*([^)]*)\)", cell).group(1).strip()
    for a, b, r, f in re.findall(r"\(IOPATH (\S+) (\S+) (\([^)]*\)) (\([^)]*\))\)", cell):
        out = re.sub(r"\[\d+\]$", "", b)
        cur = cell_d[inst].setdefault(out, [None, None])
        for k, t in ((0, r), (1, f)):
            x = val(t)
            if x is not None: cur[k] = x if cur[k] is None else pick(cur[k], x)
    for drv, load, r, f in re.findall(r"\(INTERCONNECT (\S+) (\S+) (\([^)]*\)) (\([^)]*\))\)", cell):
        drv = re.sub(r"\[\d+\]$", "", drv)
        cur = wire_d[drv]
        for k, t in ((0, r), (1, f)):
            x = val(t)
            if x is not None: cur[k] = x if cur[k] is None else pick(cur[k], x)

# ---- wrapped models ----
out_txt, wrapped = [], {}
for m in models:
    src = open(m).read()
    for mod in re.findall(r"module\s+\w+\s*\(.*?endmodule", src, flags=re.S):
        name = re.match(r"module\s+(\w+)", mod).group(1)
        if name in wrapped: continue
        decls = re.findall(r"^\s*(input|output)\s*(\[[^\]]+\])?\s*([\w\s,]+);", mod, flags=re.M)
        ports = [(d, w or "", p.strip()) for d, w, ps in decls for p in ps.split(",") if p.strip()]
        if not ports: continue
        header = re.match(r"module\s+\w+\s*\((.*?)\)\s*;", mod, flags=re.S).group(1)
        order = [p.strip() for p in header.split(",")]
        if not any(d == "output" for d, _, _ in ports): continue
        wrapped[name] = [p for d, _, p in ports if d == "output"]
        params = "".join(f"  parameter real DR_{p} = 0.0, DF_{p} = 0.0;\n" for d, _, p in ports if d == "output")
        body = "".join(f"  {d} {w} {p};\n" for d, w, p in ports)
        body += "".join(f"  wire {w} c_{p};\n  assign #(DR_{p}, DF_{p}) {p} = c_{p};\n"
                        for d, w, p in ports if d == "output")
        conn = ", ".join(f".{p}({'c_' + p if p in wrapped[name] else p})" for p in order)
        out_txt.append(f"module {name} ({', '.join(order)});\n{params}{body}  {name}__f c ({conn});\nendmodule\n")
    # rename every module of this file to M__f (instances of other models inside SRAM
    # files, such as the behavioral core, keep their names: they are not wrapped)
    src = re.sub(r"(^\s*module\s+)(\w+)", lambda g: g.group(1) + g.group(2) + ("__f" if g.group(2) in wrapped else ""), src, flags=re.M)
    out_txt.insert(0, src)
open(models_out, "w").write(
    "// GENERATED by synth/sdf_delays.py: functional models renamed M__f, wrapped by M with one\n"
    "// inertial delay per output (defparam'd from the SDF). Do not edit.\n`timescale 1ns/10ps\n"
    + "\n".join(out_txt))

# ---- netlist copy with defparams ----
net = open(nl).read()
types = dict((i, t) for t, i in re.findall(r"^\s*(\w+)\s+(\\?\S+)\s*\(", net, flags=re.M))
lines, n = [], 0
for inst, outs in cell_d.items():
    t = types.get(inst)
    if t not in wrapped: continue
    for o, (r, f) in outs.items():
        if o not in wrapped[t]: continue
        wr, wf = wire_d.get(f"{inst}.{o}", [None, None])
        r = (r or 0.0) + (wr or 0.0); f = (f or 0.0) + (wf or 0.0)
        lines.append(f"  defparam {inst}.DR_{o} = {r:.3f}; defparam {inst}.DF_{o} = {f:.3f};")
        n += 1
i = net.rindex("endmodule")
open(nl_out, "w").write(net[:i] + "\n".join(lines) + "\n" + net[i:])
print(f"{len(wrapped)} models wrapped, {n} instance outputs annotated "
      f"({'min' if pick is min else 'max'}) -> {models_out}, {nl_out}")
