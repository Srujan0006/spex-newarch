#!/usr/bin/env python3
"""Functional copy of the IHP sg13cmos5l standard-cell Verilog for the zero-delay
gate-level replay (out/tb_chip.v on the routed netlist).

The PDK models feed their flops from `delayed_<pin>` nets that only the $setuphold /
$recrem timing checks drive; Icarus 12 does not support those delayed signals and
leaves them undriven, so every flop reads Z. This writes a copy where each
`delayed_<pin>` is assigned from `<pin>` and the specify blocks are dropped. The cell
functions (primitives and UDPs) are unchanged.

usage: python3 synth/gl_cells.py <sg13cmos5l_stdcell.v> <out.v>
"""
import re, sys

src, dst = sys.argv[1], sys.argv[2]
text = open(src).read()
text = re.sub(r"\n\s*specify\b.*?\bendspecify", "", text, flags=re.S)
out, n = [], 0
for mod in re.split(r"(?<=endmodule)", text):
    names = sorted(set(re.findall(r"\bdelayed_(\w+)", mod)))
    if names:
        assigns = "".join(f"\tassign delayed_{p} = {p};\n" for p in names)
        mod = mod.replace("endmodule", assigns + "endmodule", 1)
        n += 1
    out.append(mod)
open(dst, "w").write(
    f"// GENERATED by synth/gl_cells.py from {src.split('/')[-1]}: delayed_* nets driven\n"
    "// from their pins, specify blocks removed (functional, zero delay). Do not edit.\n"
    + "".join(out))
print(f"{n} cells patched -> {dst}")
