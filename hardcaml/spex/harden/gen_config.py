"""Generate src/config.json for the new_arch harden: 6x4 (decision option C, 2026-10-24), 8x4 since 2026-11-09
(owner: more routing room; the macro placement is the 6x4 one, the extra width on the right is logic).

    python3 gen_config.py

Starts from the SPEX v1 spike's layout A config (experiments/rtl_spike/layouts/a/config.json: fp5's PDN recipe and
stripe step, macro routing obstructions, obstruction-aware CTS, 200 um repair wire length, strict global routing,
30-pass detailed routing at density 40 %) and changes only the macros and the tile. LVS, Magic stream-out / LEF and the
IR-drop report are back on (the spike skipped them): this run is for sign-off and precheck, not only timing.
  u_rec0  1P_256x64  (486.68, 3.78)    FS, pins up    } the location store, 256 x 128 bits
  u_rec1  1P_256x64  (486.68, 544.32)  N,  pins down  } (record macros on opposite edges, pins facing the logic)
  u_cov   1P_256x32  (3.36, 3.78)      FS, pins up    coverage
  corridor: placement blocked above u_rec1 (x 486.68-1271.16, y 663.10-706.86; at 6x4 it ran to the core edge). The TT I/O pins on the top edge
  (x 29.8-191.0) stay clear of it and of every macro, as in the spike (run 40074391783 put u_rec1 under the pins at
  x 3.36: the corridor then covered them and detailed placement could not place the 17 input buffers, DPL-0036).
x = 3.36 + 11.24 i keeps the macros on the stripe grid; the two 256x64 share an x range at the same x (same columns).
"""
import collections
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.join(HERE, "..", "..", "..", "experiments", "rtl_spike", "layouts", "a", "config.json")
P = "pdk_dir::libs.ref/sg13cmos5l_sram"
M64, M32 = "RM_IHPSG13_1P_256x64_c2_bm_bist", "RM_IHPSG13_1P_256x32_c2_bm_bist"
SIZE = {M64: (784.48, 118.78), M32: (416.64, 118.78)}            # LEF, IHP-Open-PDK 2bbec755
TILES = [("u_rec0", M64, 486.68, 3.78, "FS"), ("u_rec1", M64, 486.68, 544.32, "N"), ("u_cov", M32, 3.36, 3.78, "FS")]
CORE = (2.88, 3.78, 1721.28, 706.86)                                # 8x4 die 1724.16 x 710.64 (6x4: x1 1286.40)
PIN_GAP = 2.6


def macro(name):
    return {"instances": collections.OrderedDict(), "gds": [f"{P}/gds/{name}.gds"], "lef": [f"{P}/lef/{name}.lef"],
            "lib": {"nom_typ_1p20V_25C": [f"{P}/lib/{name}_typ_1p20V_25C.lib"],
                    "nom_fast_1p32V_m40C": [f"{P}/lib/{name}_fast_1p32V_m55C.lib"],
                    "nom_slow_1p08V_125C": [f"{P}/lib/{name}_slow_1p08V_125C.lib"]},
            "nl": [f"dir::{name}.v"], "spice": [f"{P}/cdl/{name}.cdl"]}


def main():
    d = json.load(open(BASE), object_pairs_hook=collections.OrderedDict)
    d.pop("//layout", None)
    d["//"] = ("new_arch (Hardcaml SPEX v0.1) at 8x4, generated by hardcaml/spex/harden/gen_config.py; do not edit. "
               "Recipe from the SPEX v1 spike's layout A (experiments/rtl_spike/layouts/a/config.json).")
    d["MACROS"] = collections.OrderedDict([(M64, macro(M64)), (M32, macro(M32))])
    obs = []
    for inst, m, x, y, o in TILES:
        w, h = SIZE[m]
        assert CORE[0] <= x and x + w <= CORE[2] and CORE[1] <= y and y + h <= CORE[3], inst
        d["MACROS"][m]["instances"][inst] = {"location": [x, y], "orientation": o}
        y0, y1 = (y, y + h - PIN_GAP) if o == "FS" else (y + PIN_GAP, y + h)
        obs += [f"{layer} {x:.2f} {y0:.2f} {x + w:.2f} {y1:.2f}" for layer in ("Metal2", "Metal3", "Metal4")]
    d["ROUTING_OBSTRUCTIONS"] = obs
    d["PDN_MACRO_CONNECTIONS"] = [f"{i} VPWR VGND {pw} VSS!" for i, *_ in TILES for pw in ("VDD!", "VDDARRAY!")]
    for k in ("RUN_LVS", "RUN_MAGIC_STREAMOUT", "RUN_MAGIC_WRITE_LEF", "RUN_IRDROP_REPORT"):
        d[k] = True
    d["FP_OBSTRUCTIONS"] = [[486.68, 544.32 + 118.78, 486.68 + SIZE[M64][0], CORE[3]]]
    os.makedirs(os.path.join(HERE, "src"), exist_ok=True)
    with open(os.path.join(HERE, "src", "config.json"), "w") as f:
        json.dump(d, f, indent=2)
        f.write("\n")
    print({i: (x, y, o) for i, _m, x, y, o in TILES}, "corridor", d["FP_OBSTRUCTIONS"])


if __name__ == "__main__":
    main()
